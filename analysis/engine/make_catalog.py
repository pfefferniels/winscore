"""Write catalog.md from names.tsv, Ghidra's call graph (analysis/data/calls.tsv, functions.tsv)
and the calls observed by oracle/trace.py on the sample scores (dynamic_calls.tsv).

    python make_catalog.py
"""
from __future__ import annotations

import csv
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATA = HERE.parent / "data"


def read_tsv(path: Path) -> list[dict[str, str]]:
    with path.open() as f:
        return list(csv.DictReader(f, delimiter="\t"))


def thunk_targets(functions: list[dict[str, str]]) -> dict[int, int]:
    """thunk_FUN_00547c32 at 0x40655A -> 0x547C32."""
    return {int(f["entry"], 16): int(f["name"].rsplit("_", 1)[1], 16)
            for f in functions if f["name"].startswith("thunk_FUN_")}


def static_callers() -> dict[int, set[int]]:
    targets = thunk_targets(read_tsv(DATA / "functions.tsv"))
    callers: dict[int, set[int]] = defaultdict(set)
    with (DATA / "calls.tsv").open() as f:
        for caller, callee in csv.reader(f, delimiter="\t"):
            if callee.startswith("EXTERNAL:"):
                continue
            c, t = int(caller, 16), int(callee, 16)
            callers[targets.get(t, t)].add(c)
    return callers


def dynamic_callers() -> dict[int, set[int]]:
    callers: dict[int, set[int]] = defaultdict(set)
    for row in read_tsv(HERE / "dynamic_calls.tsv"):
        callers[int(row["callee"], 16)].add(int(row["caller"], 16))
    return callers


def main():
    names = read_tsv(HERE / "names.tsv")
    label = {int(r["address"], 16): r["name"] for r in names}
    callers = static_callers()
    for callee, found in dynamic_callers().items():
        callers[callee] |= found - {0}

    def caller_text(address: int) -> str:
        known = sorted(callers.get(address, ()))
        shown = [label.get(c, f"{c:06x}") for c in known[:6]]
        return ", ".join(shown) + (f" (+{len(known) - 6})" if len(known) > 6 else "")

    rows = sorted(names, key=lambda r: int(r["address"], 16))
    lines = ["# Routine catalogue", "",
             "Generated by `make_catalog.py` from `names.tsv` and Ghidra's static call graph; edit `names.tsv`, not this file.",
             "Callers: static call sites (through the incremental-linking thunks) plus calls seen when tracing `G` of the four sample scores; confidence as in README.md.", "",
             "| Address | Name | Role | Callers | Confidence |", "|---|---|---|---|---|"]
    lines += [f"| `{int(r['address'], 16):06X}` | `{r['name']}` | {r['role'].replace('|', '&#124;')} | {caller_text(int(r['address'], 16))} | {r['confidence']} |"
              for r in rows]
    (HERE / "catalog.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
