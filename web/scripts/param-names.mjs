// Generates rust/crates/score-web/src/param_names.rs from the "parameter
// structure" headings of Smith's WinScore help pages
// (analysis/docs/text/winscore/code*.txt): one short label per code and
// parameter, as the help words it.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const web = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const repo = path.join(web, '..');
const docs = path.join(repo, 'analysis', 'docs', 'text', 'winscore');
const out = path.join(repo, 'rust', 'crates', 'score-web', 'src', 'param_names.rs');

const MAX_LABEL = 60;

/**
 * The lines of the parameter list, from its heading on. Entries that the
 * text conversion ran together ("left endP4 vertical") are split.
 */
function parameterSection(text) {
  const lines = text.replace(/([a-z)])(P\d{1,2}\b)/g, '$1\n$2').split(/\r?\n/);
  const start = lines.findIndex((l) => /parameter structure/i.test(l));
  return start < 0 ? [] : lines.slice(start + 1);
}

/** "8-13, 16, 17" → [8, …, 13, 16, 17] */
function numbers(first, rest) {
  const parts = `${first}${rest}`.split(',').map((p) => p.trim().split('-').map(Number));
  return parts.flatMap(([a, b = a]) => Array.from({ length: Math.max(0, b - a + 1) }, (_, i) => a + i));
}

/** `P<n>[, m…] label` entries; a label may continue on the following short lines. */
function entries(lines) {
  const found = [];
  let current = null;
  for (const raw of lines) {
    const line = raw.trim();
    const head = line.match(/^P(\d{1,2})((?:\s*[,-]\s*\d{1,2}\b)*)\s*(?:Parameter\s+\d+\s*=?\s*)?(.*)$/);
    if (head) {
      const ns = numbers(head[1], head[2]).filter((n) => n >= 1 && !found.some((e) => e.ns.includes(n)));
      current = { ns, words: head[3] ? [head[3]] : [] };
      found.push(current);
      continue;
    }
    if (!current) continue;
    if (line === '' && current.words.length > 0) {
      current = null;
      continue;
    }
    if (line.length > 0 && line.length < MAX_LABEL && current.words.join(' ').length < MAX_LABEL) current.words.push(line);
    else if (line.length >= MAX_LABEL) break;
  }
  const clean = (words) => words.join(' ').replace(/\s+/g, ' ').replace(/[\s-]+$/, '').trim();
  // A number list broken after its comma ("P7,⏎8, 9, 10 bounding box") continues the head.
  const split = ({ ns, words }) => {
    const text = clean(words);
    const more = text.match(/^[,\s]*(\d{1,2}(?:\s*[,-]\s*\d{1,2})*)\s+(.*)$/);
    return more && ns.length > 0 && /^[,\s-]/.test(text)
      ? { ns: [...ns, ...numbers(more[1], '')], label: more[2] }
      : { ns, label: text.replace(/^[-\s]+/, '') };
  };
  return found
    .map(split)
    .flatMap(({ ns, label }) => ns.map((n) => ({ n, label })))
    .filter((e) => /[a-z]/i.test(e.label) && e.label.length <= 2 * MAX_LABEL);
}

const files = fs.readdirSync(docs).filter((f) => /^code\d+\.txt$/i.test(f));
const table = files
  .map((f) => ({ code: Number(f.match(/\d+/)[0]), list: entries(parameterSection(fs.readFileSync(path.join(docs, f), 'latin1'))) }))
  .filter((t) => t.list.length > 0)
  .sort((a, b) => a.code - b.code);

const rustString = (s) => JSON.stringify(s);
const arms = table
  .flatMap(({ code, list }) => list.map(({ n, label }) => `        (${code}, ${n}) => ${rustString(label)},`))
  .join('\n');

const source = `//! Parameter labels from the "parameter structure" headings of Smith's
//! WinScore help (\`analysis/docs/text/winscore/code*.txt\`).
//!
//! Generated by \`web/scripts/param-names.mjs\`; do not edit by hand.

pub fn param_name(code: i32, n: usize) -> Option<&'static str> {
    Some(match (code, n) {
${arms}
        _ => return None,
    })
}
`;

fs.writeFileSync(out, source);
console.log(`param-names: ${table.length} codes, ${table.reduce((s, t) => s + t.list.length, 0)} labels → ${path.relative(repo, out)}`);
