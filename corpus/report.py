"""Write the generated part of corpus/REPORT.md from score-compare's status table.

    score-compare --fixtures corpus/fixtures --status corpus/fixtures/STATUS.md
    python corpus/report.py

Everything above the marker line in REPORT.md is kept as written by hand.
"""
from __future__ import annotations

import json
import re
from dataclasses import dataclass
from itertools import groupby
from operator import attrgetter
from pathlib import Path

CORPUS = Path(__file__).resolve().parent
REPORT = CORPUS / "REPORT.md"
FIXTURES = CORPUS / "fixtures"
MARKER = "<!-- generated by corpus/report.py below this line -->"
COUNT = re.compile(r"(\d+)/(\d+)(?: \+(\d+))?")


@dataclass(frozen=True)
class Tally:
    """matched/expected, plus elements only the Rust side has."""
    matched: int = 0
    expected: int = 0
    extra: int = 0

    @classmethod
    def parse(cls, text: str) -> "Tally":
        found = COUNT.search(text)
        return cls(*(int(g or 0) for g in found.groups())) if found else cls()

    def __add__(self, other: "Tally") -> "Tally":
        return Tally(self.matched + other.matched, self.expected + other.expected, self.extra + other.extra)

    def __str__(self) -> str:
        return f"{self.matched}/{self.expected}" + (f" +{self.extra}" if self.extra else "")


@dataclass(frozen=True)
class Row:
    case: str
    source: str
    state: str
    shapes: Tally
    texts: Tally
    description: str


def source_of(case: str) -> str:
    meta = json.loads((FIXTURES / case / "meta.json").read_text())
    return meta["description"].removeprefix("corpus file ").split("/")[0]


def case_rows(status: str) -> list[Row]:
    cells = ([c.strip() for c in line.strip("|").split("|")] for line in status.splitlines() if line.startswith("| corpus-"))
    return [Row(c[0], source_of(c[0]), c[1], Tally.parse(c[2]), Tally.parse(c[3]), c[-1]) for c in cells]


def by_source(rows: list[Row]) -> str:
    key = attrgetter("source")
    groups = {name: list(rs) for name, rs in groupby(sorted(rows, key=key), key=key)}
    lines = ["| source | files | valid | matching | shapes | texts |", "|---|---|---|---|---|---|"]
    lines += [
        f"| {name} | {len(rs)} | {sum(r.state != 'invalid' for r in rs)} | {sum(r.state == 'match' for r in rs)} "
        f"| {sum((r.shapes for r in rs), Tally())} | {sum((r.texts for r in rs), Tally())} |"
        for name, rs in groups.items()
    ]
    return "\n".join(lines)


def by_file(rows: list[Row]) -> str:
    lines = ["| case | state | shapes | texts | file |", "|---|---|---|---|---|"]
    lines += [f"| {r.case} | {r.state} | {r.shapes} | {r.texts} | {r.description} |" for r in rows]
    return "\n".join(lines)


def item_code_section(status: str) -> str:
    match = re.search(r"## By item code\n(.*?)\n## ", status, re.S)
    return match.group(1).strip() if match else ""


def main() -> None:
    status = (FIXTURES / "STATUS.md").read_text()
    rows = case_rows(status)
    head = REPORT.read_text().split(MARKER)[0].rstrip() if REPORT.exists() else "# Corpus report"
    generated = "\n\n".join([
        MARKER,
        "## By source\n\nCounts are matched/expected elements; `+n` = elements only the Rust side has.\n\n" + by_source(rows),
        "## By item code\n\n" + item_code_section(status),
        "## By file\n\n" + by_file(rows),
    ])
    REPORT.write_text(f"{head}\n\n{generated}\n")


if __name__ == "__main__":
    main()
