//! Keeps COMMANDS.md, the coverage table of WinScore's menu commands, in step
//! with the code. `UPDATE_COMMANDS_MD=1 cargo test -p score-edit --test commands_md`
//! rewrites it.

use std::collections::BTreeMap;
use std::path::PathBuf;

use score_edit::command::{is_supported, item};

const CASES: &str = include_str!("engine_cases.txt");
const EXPECTED: &str = include_str!("engine_expected.txt");

fn crate_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

/// Command string -> tooltips, from WinScore's menu handlers.
fn menu_commands() -> BTreeMap<String, Vec<String>> {
    let path = crate_dir().join("../../../analysis/data/command_map.tsv");
    let table = std::fs::read_to_string(path).expect("analysis/data/command_map.tsv");
    let mut commands: BTreeMap<String, Vec<String>> = BTreeMap::new();
    table.lines().skip(1).filter_map(|line| line.split('\t').nth(2).map(|c| (c, line.split('\t').nth(3)))).for_each(
        |(command, tooltip)| {
            let command = command.trim();
            if command.is_empty() {
                return;
            }
            let tips = commands.entry(command.to_owned()).or_default();
            let tip = tooltip.unwrap_or("").trim().replace('|', "/");
            if !tip.is_empty() && !tips.contains(&tip) {
                tips.push(tip);
            }
        },
    );
    commands
}

fn first_token(line: &str) -> String {
    line.split([' ', ',']).find(|t| !t.is_empty()).unwrap_or("").to_ascii_uppercase()
}

fn is_numeric(token: &str) -> bool {
    token.trim_start_matches('/').parse::<f32>().is_ok()
}

/// First words of the command lines of every case the engine has a result for.
fn verified_words() -> Vec<String> {
    let has_result: Vec<&str> = EXPECTED.lines().filter_map(|l| l.strip_prefix("== ")).map(str::trim).collect();
    let mut words = Vec::new();
    let mut current_has_result = false;
    CASES.lines().for_each(|line| {
        if let Some(name) = line.strip_prefix("== ") {
            current_has_result = has_result.contains(&name.trim());
        } else if current_has_result && !line.starts_with(['#', ' ']) && !line.starts_with("base:") && !line.trim().is_empty() {
            words.push(first_token(line));
        }
    });
    words.sort();
    words.dedup();
    words
}

fn mark(yes: bool) -> &'static str {
    if yes {
        "yes"
    } else {
        "no"
    }
}

fn render() -> String {
    let menu = menu_commands();
    let verified = verified_words();
    let numbers_verified = verified.iter().any(|w| is_numeric(w));
    let is_verified = |command: &str| {
        let token = first_token(command);
        if is_numeric(&token) {
            numbers_verified
        } else {
            verified.contains(&token)
        }
    };
    let rows: Vec<String> = menu
        .iter()
        .map(|(command, tips)| {
            let implemented = is_supported(command);
            format!(
                "| `{}` | {} | {} | {} |",
                command.replace('|', "/"),
                tips.join(" / "),
                mark(implemented),
                mark(implemented && is_verified(command))
            )
        })
        .collect();
    let implemented = menu.keys().filter(|c| is_supported(c)).count();
    let checked = menu.keys().filter(|c| is_supported(c) && is_verified(c)).count();
    let extra: Vec<String> = item::entries()
        .filter(|e| !menu.keys().any(|c| first_token(c) == e.word))
        .map(|e| format!("| `{}` | {} | yes | {} |", e.word, e.meaning, mark(verified.contains(&e.word.to_owned()))))
        .fold(Vec::new(), |mut rows, row| {
            if !rows.contains(&row) {
                rows.push(row);
            }
            rows
        });
    format!(
        "# Command coverage of score-edit\n\n\
         Generated by `tests/commands_md.rs` from `analysis/data/command_map.tsv` (the command strings \
         WinScore's menus and toolbars send, with their tooltips), the command tables of this crate and \
         the engine cases; rewrite with `UPDATE_COMMANDS_MD=1 cargo test -p score-edit --test commands_md`.\n\n\
         *Implemented*: the editor accepts the command in some context. *Verified*: a case in \
         `tests/engine_cases.txt` starting with the same word gives the same items as WinScore's engine \
         under emulation (parameter pairs count as one family). Many menu entries are display, file, \
         MIDI or dialog commands that the browser shell handles itself or that are out of scope.\n\n\
         {} distinct menu commands, {} implemented, {} of them verified.\n\n\
         | Command | Meaning (tooltip) | Implemented | Verified |\n|---|---|---|---|\n{}\n\n\
         ## Edit words not on WinScore's menus\n\n\
         Besides these, creation words follow patterns: `NOTE[D][F|S|N]`, `METERnm`, `KSIG±n[B|A|T]`, \
         `BARn`, `BEAMn`, `SLUR[D]n`, `TREM[D]n`, clef names with `M` for mini clefs.\n\n\
         | Word | Meaning | Implemented | Verified |\n|---|---|---|---|\n{}\n",
        menu.len(),
        implemented,
        checked,
        rows.join("\n"),
        extra.join("\n")
    )
}

#[test]
fn commands_md_is_current() {
    let path = crate_dir().join("COMMANDS.md");
    let fresh = render();
    if std::env::var_os("UPDATE_COMMANDS_MD").is_some() {
        std::fs::write(&path, &fresh).expect("write COMMANDS.md");
        return;
    }
    let stored = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(stored == fresh, "COMMANDS.md is out of date; rerun with UPDATE_COMMANDS_MD=1");
}
